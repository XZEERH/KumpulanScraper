#!/usr/bin/env node
'use strict';

/**
 * Name : Facebook Downloader
 * Creator : lmavour
 * Source : https://api.kyio.web.id/docs
 * Base Web : https://api.kyio.web.id
 * Type : Scraper
 * Description : Download videos from Facebook with multiple quality options and direct links.
 * Note : node scrapers/kyio/downloader/scrape-fb.js --help
 */

const { httpEndpoint } = require('../../lib/http-endpoint');
const { kyioHeaders } = require('../../lib/kyio');
const ENDPOINT = 'https://api.kyio.web.id/api/v2/downloader/fb';
const { scrape: downloaderFb, cli } = httpEndpoint(ENDPOINT, {
  source: 'kyio', headers: kyioHeaders,
  methods: ['GET'],
  params: {
    q: { required: true }
  }
});

module.exports = { downloaderFb };
if (require.main === module) cli();
