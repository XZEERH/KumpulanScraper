#!/usr/bin/env node
'use strict';

/**
 * Name : SaveFrom Downloader
 * Creator : lmavour
 * Source : https://api.kyio.web.id/docs
 * Base Web : https://api.kyio.web.id
 * Type : Scraper
 * Description : Download media using SaveFrom API.
 * Note : node scrapers/kyio/downloader/scrape-savefrom.js --help
 */

const { httpEndpoint } = require('../../lib/http-endpoint');
const { kyioHeaders } = require('../../lib/kyio');
const ENDPOINT = 'https://api.kyio.web.id/api/v2/downloader/savefrom';
const { scrape: downloaderSavefrom, cli } = httpEndpoint(ENDPOINT, {
  source: 'kyio', headers: kyioHeaders,
  methods: ['GET'],
  params: {
    url: { required: true },
    q: { required: true }
  }
});

module.exports = { downloaderSavefrom };
if (require.main === module) cli();
